%% LOCAL FUNCTIONS

function value = get_parameter(names,values,name)
    idx = names == lower(string(name));
    assert(nnz(idx) == 1, ...
        'Expected one RCAm parameter named "%s".',name);
    value = values(idx);
end

function err = check_savings_blocks(annual_path,node_path,node_idx,H_nodes)
    err = 0;
    for kk = 1:H_nodes-1
        block = node_idx(kk):(node_idx(kk+1)-1);
        err = max(err,max(abs(annual_path(block)-node_path(kk))));
    end
    err = max(err,abs(annual_path(end)-node_path(end)));
end

function Data = make_simulation_data( ...
    H,K0,depreciation,tfp,population,labour_share, ...
    capital_share,omega,prstp,elasmu,consumption_floor)

    Data.H = H;
    Data.initial_capital = K0;
    Data.depreciation = depreciation;
    Data.tfp = tfp;
    Data.population = population;
    Data.labour_share = labour_share;
    Data.capital_share = capital_share;
    Data.omega = omega;
    Data.discount_factor = 1./((1+prstp).^((0:H-1)'));
    Data.elasmu = elasmu;
    Data.consumption_floor = consumption_floor;
end

function objective_value = regional_savings_objective(decision,Data)
    [~,annual_path] = build_savings_paths(decision,Data);
    [~,~,~,~,~,welfare] = ...
        simulate_regional_economy(annual_path,Data);
    if isfinite(welfare)
        objective_value = -welfare;
    else
        objective_value = 1e30;
    end
end

function [node_path,annual_path] = build_savings_paths(decision,Data)
    decision = decision(:);
    assert(numel(decision) == Data.terminal_start-2, ...
        'The five-year savings decision vector has the wrong length.');

    node_path = zeros(Data.H_dice,1);
    node_path(1) = Data.savings_initial;
    node_path(2:Data.terminal_start-1) = decision;
    node_path(Data.terminal_start:end) = Data.terminal_savings;

    annual_path = node_path(Data.node_index_annual);
end

function [capital,gross_output,net_output,investment,consumption,welfare] = ...
    simulate_regional_economy(savings_path,Data)

    savings_path = savings_path(:);
    capital = zeros(Data.H,1);
    gross_output = zeros(Data.H,1);
    net_output = zeros(Data.H,1);
    investment = zeros(Data.H,1);
    consumption = zeros(Data.H,1);
    capital(1) = Data.initial_capital;
    welfare = -Inf;

    for aa = 1:Data.H
        if ~isfinite(capital(aa)) || capital(aa) <= 0
            return;
        end

        gross_output(aa) = Data.tfp(aa).* ...
            (Data.population(aa)/1000).^Data.labour_share.* ...
            capital(aa).^Data.capital_share;
        net_output(aa) = gross_output(aa)./(1+Data.omega(aa));
        investment(aa) = savings_path(aa).*net_output(aa);
        consumption(aa) = net_output(aa)-investment(aa);

        if ~isfinite(consumption(aa)) || ...
                consumption(aa) <= Data.consumption_floor
            return;
        end

        if aa < Data.H
            capital(aa+1) = ...
                (1-Data.depreciation).*capital(aa)+investment(aa);
        end
    end

    consumption_per_person = consumption./Data.population;

    if abs(Data.elasmu-1) < 1e-12
        period_utility = log(consumption_per_person);
    else
        period_utility = ...
            consumption_per_person.^(1-Data.elasmu)./(1-Data.elasmu);
    end

    welfare = sum(Data.discount_factor.* ...
        Data.population.*period_utility);
end

function export_plot_overwrite(fig,plots_dir,filename)
    output_file = fullfile(plots_dir,filename);
    if isfile(output_file)
        delete(output_file);
    end
    exportgraphics(fig,output_file,'Resolution',300);
    assert(isfile(output_file),'Plot export failed: %s',output_file);
end
