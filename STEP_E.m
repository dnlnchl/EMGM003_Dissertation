%% RUN ANNUAL HURRICANE SIMULATIONS

% Work through the regional economy one year at a time.
% Hurricanes affect the year in which they occur. The lower investment that
% follows from the output loss then affects the capital stock in later years.

for aa = 1:H_annual

    % Only simulations containing a hurricane need category draws.
    affected_sims = ...
        find(NumHurricanesAnnual_stoch(aa,:) > 0);


    for jj = 1:numel(affected_sims)

        sim = affected_sims(jj);

        n_events = ...
            double(NumHurricanesAnnual_stoch(aa,sim));


        % Draw a category for each hurricane using that year's probabilities.
        u = rand(n_events,1);

        category_index = ...
            1+sum(u > cat_cdf_annual(aa,:),2);


        % Convert the categories into the calibrated loss shares.
        event_losses = ...
            hurricane_loss_share_by_cat(category_index);


        % If more than one storm occurs in a year, losses are compounded
        % rather than averaged.
        HurricaneAnnualLossShare_stoch(aa,sim) = ...
            1-prod(1-event_losses);


        % Record how many storms occurred in each category.
        category_counts = ...
            accumarray(category_index,1,[5 1]);

        CategoryCountsAnnual_stoch(aa,sim,:) = ...
            reshape(uint16(category_counts),1,1,5);

    end


    % Gross output is determined using the capital available at the start
    % of the current year.
    Ygross_hurr_stoch(aa,:) = ...
        tfp_annual(aa).* ...
        (pop_annual(aa)/1000).^labour_share_reg.* ...
        K_hurr_stoch(aa,:).^capital_share_reg;


    % Regional emissions are derived from gross output and the fixed global
    % DICE abatement pathway.
    EIND_hurr_stoch(aa,:) = ...
        carbon_intensity_annual(aa).* ...
        (1-abaterate_annual(aa)).* ...
        Ygross_hurr_stoch(aa,:).* ...
        ppp2mer_reg;


    % First apply the chronic regional temperature impact.
    Ynet_temperature_sameK_stoch(aa,:) = ...
        Ygross_hurr_stoch(aa,:)./(1+omega_annual(aa));


    % Then apply the realised hurricane loss in that calendar year.
    Ynet_hurr_stoch(aa,:) = ...
        Ynet_temperature_sameK_stoch(aa,:).* ...
        (1-HurricaneAnnualLossShare_stoch(aa,:));


    % Additional output loss caused by hurricanes alone.
    HurricaneAdditionalLossPct_stoch(aa,:) = ...
        100.*( ...
        1-Ynet_hurr_stoch(aa,:)./ ...
        Ynet_temperature_sameK_stoch(aa,:));


    % Savings remains fixed at the Step C pathway.
    Investment_hurr_stoch(aa,:) = ...
        savings_policy_annual(aa).* ...
        Ynet_hurr_stoch(aa,:);


    Consumption_hurr_stoch(aa,:) = ...
        Ynet_hurr_stoch(aa,:)- ...
        Investment_hurr_stoch(aa,:);


    % Keep consumption positive if an extreme simulated loss pushes it
    % below the numerical floor.
    low_consumption = ...
        Consumption_hurr_stoch(aa,:) <= ...
        Params.consumption_floor;


    if any(low_consumption)

        Consumption_hurr_stoch(aa,low_consumption) = ...
            Params.consumption_floor;

        Investment_hurr_stoch(aa,low_consumption) = max( ...
            Ynet_hurr_stoch(aa,low_consumption)- ...
            Params.consumption_floor,0);

    end


    % Total output gap relative to the no-temperature-impact,
    % no-hurricane economy.
    TotalOutputGapPct_hurr_stoch(aa,:) = ...
        100.*( ...
        Ygross_nodamage_annual(aa)- ...
        Ynet_hurr_stoch(aa,:))./ ...
        Ygross_nodamage_annual(aa);


    % Today's investment contributes to next year's capital stock.
    if aa < H_annual

        K_hurr_stoch(aa+1,:) = ...
            (1-depreciation_reg).* ...
            K_hurr_stoch(aa,:) + ...
            Investment_hurr_stoch(aa,:);

    end

end


%% CALCULATE WELFARE

% Calculate welfare separately for each complete hurricane history.

discfactor_reg_annual = ...
    1./((1+prstp_reg).^((0:H_annual-1)'));


for sim = 1:NSIMS

    consumption_per_person = ...
        Consumption_hurr_stoch(:,sim)./ ...
        pop_annual;


    if abs(elasmu_reg-1) < 1e-12

        utility_hurr_sim = ...
            log(consumption_per_person);

    else

        utility_hurr_sim = ...
            consumption_per_person.^(1-elasmu_reg)./ ...
            (1-elasmu_reg);

    end


    Welfare_hurr_stoch(sim) = ...
        sum( ...
        discfactor_reg_annual.* ...
        pop_annual.* ...
        utility_hurr_sim);

end


