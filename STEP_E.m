%% MONTE CARLO INITIALISATION

% Preallocate the main simulation arrays.
% Rows are years and columns are hurricane histories.

assert(exist('poissrnd','file') == 2, ...
    ['Step E requires poissrnd from the Statistics and ' ...
    'Machine Learning Toolbox.']);


K_hurr_stoch = ...
    zeros(H_annual,NSIMS);

Ygross_hurr_stoch = ...
    zeros(H_annual,NSIMS);

EIND_hurr_stoch = ...
    zeros(H_annual,NSIMS);

Ynet_temperature_sameK_stoch = ...
    zeros(H_annual,NSIMS);

Ynet_hurr_stoch = ...
    zeros(H_annual,NSIMS);

Investment_hurr_stoch = ...
    zeros(H_annual,NSIMS);

Consumption_hurr_stoch = ...
    zeros(H_annual,NSIMS);


HurricaneAnnualLossShare_stoch = ...
    zeros(H_annual,NSIMS);

HurricaneAdditionalLossPct_stoch = ...
    zeros(H_annual,NSIMS);

TotalOutputGapPct_hurr_stoch = ...
    zeros(H_annual,NSIMS);


% Draw the number of hurricanes occurring in every year of every history.

NumHurricanesAnnual_stoch = uint16( ...
    poissrnd(local_rate,H_annual,NSIMS));


% Store how many Cat 1, 2, 3, 4 and 5 storms occur in each year.

CategoryCountsAnnual_stoch = ...
    zeros(H_annual,NSIMS,5,'uint16');


Welfare_hurr_stoch = ...
    zeros(NSIMS,1);


% Every simulation begins with the same initial RCAm capital stock.

K_hurr_stoch(1,:) = ...
    initial_capital_reg;


