cat_probs = ...
    cat_probs./sum(cat_probs);


%% TEMPERATURE-DEPENDENT HURRICANE INTENSITY

% Hurricane frequency stays fixed. Warming only changes the mix of storm
% categories by shifting some probability towards Categories 4 and 5.
%
% The combined Category 4-5 probability rises by 13% for every 2 degrees C
% of regional warming relative to 2015.

temperature_intensity_reference = ...
    T_region_annual(1);

intensity_temperature_change = max( ...
    T_region_annual-temperature_intensity_reference,0);

cat45_relative_change_at_2C = 0.13;

cat45_relative_change_per_degree = ...
    cat45_relative_change_at_2C/2;


% Separate non-major and major hurricane probabilities.

baseline_nonmajor_probability = ...
    sum(cat_probs(1:3));

baseline_major_probability = ...
    sum(cat_probs(4:5));

assert(baseline_nonmajor_probability > 0 && ...
    baseline_major_probability > 0, ...
    'Both nonmajor and major baseline probabilities must be positive.');


% Increase the Cat 4-5 share as regional temperature rises.

major_probability_annual = ...
    baseline_major_probability.*( ...
    1+cat45_relative_change_per_degree.* ...
    intensity_temperature_change);

major_probability_annual = ...
    min(major_probability_annual,0.999999);

nonmajor_probability_annual = ...
    1-major_probability_annual;


% Keep the relative split within Cats 1-3 and Cats 4-5 unchanged.

cat_probs_annual = ...
    zeros(H_annual,5);

cat_probs_annual(:,1:3) = ...
    nonmajor_probability_annual.* ...
    (cat_probs(1:3)./baseline_nonmajor_probability);

cat_probs_annual(:,4:5) = ...
    major_probability_annual.* ...
    (cat_probs(4:5)./baseline_major_probability);

cat_probs_annual = ...
    cat_probs_annual./sum(cat_probs_annual,2);


% CDF used later when drawing a category for each simulated storm.

cat_cdf_annual = ...
    cumsum(cat_probs_annual,2);

cat_cdf_annual(:,5) = 1;


assert(all(cat_probs_annual(:) >= 0) && ...
    all(abs(sum(cat_probs_annual,2)-1) < 1e-12), ...
    'Annual category probabilities are invalid.');


% Check the expected annual loss implied by the calibration.

conditional_mean_event_loss = ...
    sum(cat_probs.*hurricane_loss_share_by_cat);

expected_annual_loss_linear = ...
    local_rate.*conditional_mean_event_loss;

expected_annual_loss_compound = ...
    1-exp(-expected_annual_loss_linear);


% The expected loss changes slightly over time because the category mix
% becomes more severe with regional warming.

conditional_mean_event_loss_annual = ...
    cat_probs_annual*hurricane_loss_share_by_cat';

expected_annual_loss_linear_annual = ...
    local_rate.*conditional_mean_event_loss_annual;

expected_annual_loss_compound_annual = ...
    1-exp(-expected_annual_loss_linear_annual);

expected_horizon_mean_annual_loss = ...
    mean(expected_annual_loss_compound_annual);


