%% LOCAL FUNCTION

% Helper for saving figures without leaving older versions behind.

function export_plot_overwrite(fig,plots_dir,filename)

    output_file = ...
        fullfile(plots_dir,filename);


    if isfile(output_file)

        delete(output_file);

    end


    exportgraphics( ...
        fig, ...
        output_file, ...
        'Resolution',300);


    assert(isfile(output_file), ...
        'Plot export failed: %s',output_file);

end