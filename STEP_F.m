% COMPRESS_LOSS_DISTRIBUTION
% Reduce thousands of simulated annual hurricane losses to a small set
% of representative loss nodes and probability weights for the Bellman
% expectation. Zero-loss years are retained explicitly; positive losses
% are sorted into approximately equal-sized bins.
%
function [nodes,weights,omitted_probability,mean_error] = ...
    compress_loss_distribution( ...
    losses,counts,max_count,max_positive_nodes)

    losses = losses(:);
    counts = counts(:);

    retained = counts <= max_count;

    omitted_probability = mean(~retained);

    retained_losses = losses(retained);

    assert(~isempty(retained_losses), ...
        'No hurricane observations remain after count truncation.');

    zero_count = sum(retained_losses == 0);

    positive_losses = ...
        sort(retained_losses(retained_losses > 0));

    retained_count = numel(retained_losses);

    nodes = zeros(0,1);
    weights = zeros(0,1);

    if zero_count > 0
        nodes(end+1,1) = 0;

        weights(end+1,1) = ...
            zero_count./retained_count;
    end

    if ~isempty(positive_losses)

        number_bins = min( ...
            max_positive_nodes,numel(positive_losses));

        edges = round(linspace( ...
            0,numel(positive_losses),number_bins+1));

        for bb = 1:number_bins

            bin_indices = ...
                (edges(bb)+1):edges(bb+1);

            if isempty(bin_indices)
                continue;
            end

            nodes(end+1,1) = ...
                mean(positive_losses(bin_indices)); %#ok<AGROW>

            weights(end+1,1) = ...
                numel(bin_indices)./retained_count; %#ok<AGROW>
        end
    end

    weights = weights./sum(weights);

    retained_mean = mean(retained_losses);
    compressed_mean = sum(nodes.*weights);

    mean_error = compressed_mean-retained_mean;
end

% FIXED_SAVINGS_CONTINUATION
% Approximate welfare beyond the explicit model horizon under a fixed
% terminal savings rate. Iterates on the continuation value until the
% value function converges on the capital grid.
%
function [continuation_value,iterations] = ...
    fixed_savings_continuation( ...
    Data,capital_grid,savings_rate, ...
    loss_nodes,loss_weights,tolerance,max_iter)

    loss_nodes = loss_nodes(:)';
    loss_weights = loss_weights(:);

    continuation_value = ...
        zeros(numel(capital_grid),1);

    terminal_tfp = Data.tfp(end);
    terminal_population = Data.population(end);
    terminal_omega = Data.omega(end);

    for iterations = 1:max_iter

        updated_value = ...
            zeros(size(continuation_value));

        for kk = 1:numel(capital_grid)

            capital = capital_grid(kk);

            gross_output = terminal_tfp.* ...
                (terminal_population./1000).^Data.labour_share.* ...
                capital.^Data.capital_share;

            temperature_output = ...
                gross_output./(1+terminal_omega);

            net_output = ...
                temperature_output.*(1-loss_nodes);

            consumption = ...
                (1-savings_rate).*net_output;

            next_capital = ...
                Data.depreciation_factor.*capital+ ...
                savings_rate.*net_output;

            next_capital = min(max( ...
                next_capital,capital_grid(1)), ...
                capital_grid(end));

            future_value = interp1( ...
                capital_grid,continuation_value, ...
                next_capital,'linear');

            utility = period_utility( ...
                consumption,terminal_population, ...
                Data.elasmu,Data.consumption_floor);

            updated_value(kk) = ...
                (utility+Data.beta.*future_value)* ...
                loss_weights;
        end

        difference = ...
            max(abs(updated_value-continuation_value));

        scale = max(1,max(abs(updated_value)));

        continuation_value = updated_value;

        if difference <= tolerance.*scale
            return;
        end
    end

    error('Terminal continuation value did not converge.');
end

% SOLVE_BELLMAN_POLICY
% Solve the finite-horizon Bellman problem by backward induction.
% For every year and capital state, evaluate all permitted savings choices
% across the relevant hurricane-loss nodes and retain the choice with the
% highest expected current utility plus discounted continuation value.
%
function [value_function,policy_savings,boundary_clamps] = ...
    solve_bellman_policy( ...
    Data,capital_grid,savings_grid, ...
    loss_nodes,loss_weights,continuation_value)

    NK_local = numel(capital_grid);

    value_function = zeros(Data.H,NK_local);
    policy_savings = zeros(Data.H,NK_local);

    boundary_clamps = 0;

    for tt = Data.H:-1:1

        if tt == Data.H
            next_value = continuation_value;
        else
            next_value = value_function(tt+1,:)';
        end

        if tt == 1
            choices = Data.initial_savings;
        elseif tt >= Data.terminal_start
            choices = Data.terminal_savings;
        else
            choices = savings_grid;
        end

        losses = loss_nodes{tt}(:)';
        weights = loss_weights{tt}(:);

        for kk = 1:NK_local

            capital = capital_grid(kk);

            gross_output = Data.tfp(tt).* ...
                (Data.population(tt)./1000).^Data.labour_share.* ...
                capital.^Data.capital_share;

            temperature_output = ...
                gross_output./(1+Data.omega(tt));

            net_output = ...
                temperature_output.*(1-losses);

            consumption = ...
                (1-choices).*net_output;

            next_capital = ...
                Data.depreciation_factor.*capital+ ...
                choices.*net_output;

            boundary_clamps = boundary_clamps+sum( ...
                next_capital(:) < capital_grid(1) | ...
                next_capital(:) > capital_grid(end));

            next_capital = min(max( ...
                next_capital,capital_grid(1)), ...
                capital_grid(end));

            current_utility = period_utility( ...
                consumption,Data.population(tt), ...
                Data.elasmu,Data.consumption_floor);

            future_value = interp1( ...
                capital_grid,next_value, ...
                next_capital,'linear');

            choice_values = ...
                (current_utility+ ...
                Data.beta.*future_value)*weights;

            [value_function(tt,kk),best_choice] = ...
                max(choice_values);

            policy_savings(tt,kk) = ...
                choices(best_choice);
        end
    end
end

% PERIOD_UTILITY
% CRRA utility used by the regional planner. Utility is population-weighted
% and is evaluated using consumption per person. Invalid/non-positive
% consumption receives a very large negative penalty.
%
function utility = period_utility( ...
    consumption,population,elasmu,floor_value)

    invalid = ...
        ~isfinite(consumption) | ...
        consumption <= floor_value;

    consumption = max(consumption,floor_value);

    consumption_per_person = ...
        consumption./population;

    if abs(elasmu-1) < 1e-12

        utility = population.* ...
            log(consumption_per_person);

    else

        utility = population.* ...
            consumption_per_person.^(1-elasmu)./ ...
            (1-elasmu);
    end

    utility(invalid) = -1e30;
end

% ADD_TERMINAL_CONTINUATION
% Add the discounted post-horizon continuation value to the welfare
% generated during the explicit annual simulation.
%
function welfare = add_terminal_continuation( ...
    welfare,last_capital,last_investment, ...
    Data,capital_grid,continuation_value)

    next_capital = ...
        Data.depreciation_factor.*last_capital+ ...
        last_investment;

    next_capital = min(max( ...
        next_capital,capital_grid(1)), ...
        capital_grid(end));

    continuation = interp1( ...
        capital_grid,continuation_value, ...
        next_capital,'linear');

    welfare = welfare+ ...
        Data.beta.^Data.H.*continuation(:);
end

% SIMULATE_POLICY
% Run one savings rule forward across all evaluation histories.
% If feedback_policy is empty, fixed_savings is used. Otherwise the
% year-specific Bellman savings rule is interpolated at realised capital.
%
% Timing within each year:
%   1. observe beginning-of-year capital;
%   2. select savings;
%   3. calculate gross output and chronic temperature impact;
%   4. realise the hurricane output loss;
%   5. allocate net output to consumption and investment;
%   6. carry investment into next year's capital.
%

function [capital,gross_output,temperature_output, ...
    net_output,investment,consumption, ...
    savings_realised,welfare,grid_clamps] = ...
    simulate_policy( ...
    Data,capital_grid,feedback_policy, ...
    fixed_savings,hurricane_loss)

    [H_loss,N_paths] = size(hurricane_loss);

    assert(H_loss == Data.H, ...
        'The hurricane histories do not match the annual horizon.');

    capital = zeros(Data.H,N_paths);
    gross_output = zeros(Data.H,N_paths);
    temperature_output = zeros(Data.H,N_paths);
    net_output = zeros(Data.H,N_paths);
    investment = zeros(Data.H,N_paths);
    consumption = zeros(Data.H,N_paths);
    savings_realised = zeros(Data.H,N_paths);

    capital(1,:) = Data.initial_capital;

    grid_clamps = 0;

    for tt = 1:Data.H

        if isempty(feedback_policy)

            savings_realised(tt,:) = ...
                fixed_savings(tt);

        else

            grid_clamps = grid_clamps+sum( ...
                capital(tt,:) < capital_grid(1) | ...
                capital(tt,:) > capital_grid(end));

            policy_capital = min(max( ...
                capital(tt,:),capital_grid(1)), ...
                capital_grid(end));

            savings_realised(tt,:) = interp1( ...
                capital_grid,feedback_policy(tt,:)', ...
                policy_capital,'linear');
        end

        gross_output(tt,:) = Data.tfp(tt).* ...
            (Data.population(tt)./1000).^Data.labour_share.* ...
            capital(tt,:).^Data.capital_share;

        temperature_output(tt,:) = ...
            gross_output(tt,:)./(1+Data.omega(tt));

        net_output(tt,:) = ...
            temperature_output(tt,:).*( ...
            1-hurricane_loss(tt,:));

        investment(tt,:) = ...
            savings_realised(tt,:).*net_output(tt,:);

        consumption(tt,:) = ...
            net_output(tt,:)-investment(tt,:);

        assert(all( ...
            consumption(tt,:) > Data.consumption_floor), ...
            'A forward simulation produced nonpositive consumption.');

        if tt < Data.H

            capital(tt+1,:) = ...
                Data.depreciation_factor.*capital(tt,:)+ ...
                investment(tt,:);
        end
    end

    period_values = period_utility( ...
        consumption,Data.population, ...
        Data.elasmu,Data.consumption_floor);

    discount_factor = ...
        Data.beta.^((0:Data.H-1)');

    welfare = ...
        sum(discount_factor.*period_values,1)';
end

% LOWER_TAIL_STATISTICS
% Sort outcomes from lowest to highest and return both the cutoff
% defining the worst N observations and their average. Works with
% either one vector of outcomes or a matrix with histories by row.
%
function [cutoff,tail_average,tail_values] = ...
    lower_tail_statistics(values,number_tail)

    assert(number_tail >= 1, ...
        'At least one observation is required in the lower tail.');

    if isvector(values)
        sorted_values = sort(values(:),'ascend');

        assert(number_tail <= numel(sorted_values), ...
            'The requested lower tail exceeds the available observations.');

        tail_values = sorted_values(1:number_tail);
        cutoff = tail_values(end);
        tail_average = mean(tail_values);
    else
        sorted_values = sort(values,2,'ascend');

        assert(number_tail <= size(sorted_values,2), ...
            'The requested lower tail exceeds the available observations.');

        tail_values = sorted_values(:,1:number_tail);
        cutoff = tail_values(:,end);
        tail_average = mean(tail_values,2);
    end
end

% UPPER_TAIL_STATISTICS
% Equivalent tail calculation for variables where HIGH values are
% adverse, such as percentage output losses.
%
function [cutoff,tail_average,tail_values] = ...
    upper_tail_statistics(values,number_tail)

    assert(number_tail >= 1, ...
        'At least one observation is required in the upper tail.');

    if isvector(values)
        sorted_values = sort(values(:),'descend');

        assert(number_tail <= numel(sorted_values), ...
            'The requested upper tail exceeds the available observations.');

        tail_values = sorted_values(1:number_tail);
        cutoff = tail_values(end);
        tail_average = mean(tail_values);
    else
        sorted_values = sort(values,2,'descend');

        assert(number_tail <= size(sorted_values,2), ...
            'The requested upper tail exceeds the available observations.');

        tail_values = sorted_values(:,1:number_tail);
        cutoff = tail_values(:,end);
        tail_average = mean(tail_values,2);
    end
end

