% Grid-clamp shares indicate how often simulated capital leaves the
% pre-specified Bellman grid. A very small share supports grid adequacy.
evaluation_states = H_annual.*N_EVAL;

no_risk_clamp_share = ...
    no_risk_grid_clamps./evaluation_states;

hurricane_clamp_share = ...
    hurricane_grid_clamps./evaluation_states;

assert(no_risk_clamp_share < 1e-3 && ...
    hurricane_clamp_share < 1e-3, ...
