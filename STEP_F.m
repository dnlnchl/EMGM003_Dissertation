%% ZERO-HURRICANE RECONSTRUCTION CHECK
%
% Validation check: remove hurricane losses and run the fixed reference
% savings pathway through the Step F simulator. The resulting capital,
% output and consumption paths should reproduce the deterministic
% Chapter 2 economy to numerical precision.

zero_loss = zeros(H_annual,1);

[K_reconstructed,~,~,Ynet_reconstructed,~, ...
    C_reconstructed,~,~,~] = ...
    simulate_policy( ...
    ModelData,capital_grid,[], ...
    savings_reference_annual,zero_loss);

reconstruction_error = max([ ...
    max(abs(K_reconstructed-K_step_c_annual)); ...
    max(abs(Ynet_reconstructed-Ynet_step_c_annual)); ...
    max(abs(C_reconstructed-C_step_c_annual))]);

assert(reconstruction_error < 1e-9, ...
    'The fixed reference case does not reconstruct the Chapter 2 economy.');

