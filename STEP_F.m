available_simulations = size(hurricane_loss_all,2);

%% TRAINING AND EVALUATION HISTORIES
%
% The hurricane histories are split into two non-overlapping samples.
%
%   Training sample:   used to approximate the annual hurricane-loss
%                      distribution inside the Bellman problem.
%   Evaluation sample: used only after the policies have been solved.
%

N_TRAIN = 5000;
N_EVAL = 10000;

assert(available_simulations >= N_TRAIN + N_EVAL, ...
    'Step F requires at least 15,000 independent histories.');

rng(random_seed);

% Randomise history order before assigning training and evaluation sets.
sample_order = randperm(available_simulations);

training_indices = sample_order(1:N_TRAIN);

evaluation_indices = sample_order( ...
    N_TRAIN+1:N_TRAIN+N_EVAL);

assert(isempty(intersect( ...
    training_indices,evaluation_indices)), ...
    'Training and evaluation histories must be disjoint.');

hurricane_loss_train = ...
    hurricane_loss_all(:,training_indices);

hurricane_count_train = ...
    hurricane_count_all(:,training_indices);

hurricane_loss_eval = ...
    hurricane_loss_all(:,evaluation_indices);

%% BUILD THE ANNUAL BELLMAN LOSS DISTRIBUTIONS
%
% The Bellman solver cannot efficiently evaluate thousands of realised
% losses at every capital-savings combination. The training histories
% are therefore compressed into a small set of representative annual
% loss nodes and probability weights.
%
% Years with more than max_hurricanes_bellman storms are excluded from
% the approximation. The code checks that the omitted probability is
% negligible and that the compressed distribution preserves the mean.

loss_nodes = cell(H_annual,1);
loss_weights = cell(H_annual,1);

omitted_probability = zeros(H_annual,1);
distribution_mean_error = zeros(H_annual,1);

for tt = 1:H_annual

    [loss_nodes{tt},loss_weights{tt}, ...
        omitted_probability(tt), ...
        distribution_mean_error(tt)] = ...
        compress_loss_distribution( ...
        hurricane_loss_train(tt,:), ...
        hurricane_count_train(tt,:), ...
        max_hurricanes_bellman, ...
        max_positive_loss_nodes);
end

assert(max(omitted_probability) < 1e-3, ...
    'The probability excluded by the four-storm truncation is too large.');

assert(max(abs(distribution_mean_error)) < 1e-10, ...
    'The compressed annual loss nodes do not preserve the retained mean.');

