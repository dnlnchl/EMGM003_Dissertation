
%% ========================================================================
% STEP F: ANNUAL BELLMAN SAVINGS UNDER HURRICANE RISK
% ========================================================================
%
% Builds on the DICE-2016R-conditioned annual RCAm economy and the
% stochastic hurricane histories generated in Chapter 3. A Bellman problem
% selects the annual regional savings rate based on beginning-of-year
% capital.
%
% Two feedback policies are compared: one that responds to capital without
% anticipating future hurricanes and one that incorporates the expected
% annual hurricane-loss distribution. Both policies are evaluated using
% the same separate out-of-sample hurricane histories.
%
% The five-year savings pathway from Chapter 2 is retained only as a
% reconstruction benchmark. The principal comparison is the
% hurricane-risk-aware policy relative to the policy without hurricane
% anticipation. Monte Carlo evaluation reports the 5th-percentile cutoff
% and the average within the worst 5% of outcomes.
% ========================================================================

%
% STEP F ROADMAP
% --------------
% 1. Load the deterministic annual RCAm economy from Chapter 2.
% 2. Load the annual hurricane histories from Chapter 3.
% 3. Split hurricane histories into training and evaluation samples.
% 4. Compress the training losses into Bellman probability nodes.
% 5. Build capital and savings grids and terminal continuation values.
% 6. Solve two annual feedback savings policies by backward induction.
% 7. Evaluate all policies on identical out-of-sample hurricane histories.
% 8. Validate the reconstruction, calculate mean/tail outcomes and welfare.
% 9. Export tables, figures and the final Step F workspace.
%
clearvars;
clc;
close all;

%% USER CONFIGURATION & DIRECTORY SETUP
