%% SUMMARY STATISTICS
%
% Summarise mean outcomes and lower-tail outcomes across the evaluation
% histories.
%
% For output, capital, consumption and welfare, the adverse tail is the
% LOWER 5% of outcomes. For output-gap percentages, the adverse tail is
% the UPPER 5% because larger losses are worse.
%
% Two tail measures are reported:
%   cutoff       = boundary of the worst 5%;
%   tail average = mean outcome within the worst 5%.

mean_savings_reference = ...
    mean(Savings_reference_realised,2);

mean_savings_no_risk = ...
    mean(Savings_no_risk_realised,2);

mean_savings_hurricane_risk = ...
    mean(Savings_hurricane_risk_realised,2);

mean_output_reference = mean(Ynet_reference,2);
mean_output_no_risk = mean(Ynet_no_risk,2);

mean_output_hurricane_risk = ...
    mean(Ynet_hurricane_risk,2);

% Convert the 5% tail share into an integer number of evaluation histories.
number_tail_evaluation = ceil(tail_probability.*N_EVAL);

% For output, capital, consumption and welfare, adverse outcomes are the
% lowest observations. The cutoff is the last observation included in the
% ranked worst 5%; the tail average uses only those observations.

[output_cutoff_reference,output_tail_average_reference] = ...
    lower_tail_statistics( ...
    Ynet_reference,number_tail_evaluation);

[output_cutoff_no_risk,output_tail_average_no_risk] = ...
    lower_tail_statistics( ...
    Ynet_no_risk,number_tail_evaluation);

[output_cutoff_hurricane_risk, ...
    output_tail_average_hurricane_risk] = ...
    lower_tail_statistics( ...
    Ynet_hurricane_risk,number_tail_evaluation);

[capital_cutoff_reference,capital_tail_average_reference] = ...
    lower_tail_statistics( ...
    K_reference,number_tail_evaluation);

[capital_cutoff_no_risk,capital_tail_average_no_risk] = ...
    lower_tail_statistics( ...
    K_no_risk,number_tail_evaluation);

[capital_cutoff_hurricane_risk, ...
    capital_tail_average_hurricane_risk] = ...
    lower_tail_statistics( ...
    K_hurricane_risk,number_tail_evaluation);

[consumption_cutoff_reference, ...
    consumption_tail_average_reference] = ...
    lower_tail_statistics( ...
    Consumption_reference,number_tail_evaluation);

[consumption_cutoff_no_risk, ...
    consumption_tail_average_no_risk] = ...
    lower_tail_statistics( ...
    Consumption_no_risk,number_tail_evaluation);

[consumption_cutoff_hurricane_risk, ...
    consumption_tail_average_hurricane_risk] = ...
    lower_tail_statistics( ...
    Consumption_hurricane_risk,number_tail_evaluation);

% For output gaps, adverse outcomes are the highest observations.

[output_gap_cutoff_reference, ...
