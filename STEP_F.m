continuation_tolerance = 1e-9;
continuation_max_iterations = 5000;

% Fixed seed makes the train/evaluation split reproducible.
random_seed = 6685;

% Lower-tail share used throughout the analysis (5%).
tail_probability = 0.05;

assert(NK >= 50 && NS >= 51, ...
    'The Bellman grids are too small.');

assert(savings_min >= 0 && savings_max < 1 && ...
    savings_min < savings_max, ...
    'The savings bounds are invalid.');

assert(tail_probability > 0 && tail_probability < 0.5, ...
    'The tail probability must lie between zero and one half.');

