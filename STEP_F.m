    max_hurricanes_bellman);

fprintf('Training histories:            %d\n',N_TRAIN);
fprintf('Evaluation histories:          %d\n',N_EVAL);

fprintf('Maximum omitted probability:   %.3e\n', ...
    max(omitted_probability));

%% COMMON ANNUAL ECONOMIC DATA AND GRIDS
%
% Collect the annual RCAm parameters needed by the Bellman functions
% into one structure (ModelData), then construct:
%
%   capital_grid : possible beginning-of-year capital states;
%   savings_grid : possible annual savings choices.
%
% A logarithmic capital grid provides more resolution at lower capital
% levels while still covering the upper part of the simulated range.

ModelData.H = H_annual;
ModelData.tfp = tfp_annual;
ModelData.population = pop_annual;

ModelData.labour_share = labour_share_reg;
ModelData.capital_share = capital_share_reg;
ModelData.depreciation_factor = 1-depreciation_reg;

ModelData.omega = omega_annual;
ModelData.initial_capital = initial_capital_reg;

% Convert the annual pure rate of time preference into a discount factor.
ModelData.beta = 1./(1+prstp_reg);
ModelData.elasmu = elasmu_reg;
ModelData.consumption_floor = Params.consumption_floor;

ModelData.initial_savings = savings_reference_annual(1);
ModelData.terminal_start = terminal_start_annual;
ModelData.terminal_savings = terminal_savings;

capital_grid_min = ...
    capital_grid_min_multiplier.*initial_capital_reg;

capital_grid_max = ...
    capital_grid_max_multiplier.*K_reference_max;

% Log spacing concentrates more grid points where capital is relatively low.
capital_grid = exp(linspace( ...
    log(capital_grid_min), ...
    log(capital_grid_max),NK))';

savings_grid = ...
    linspace(savings_min,savings_max,NS)';

assert(initial_capital_reg > capital_grid(1) && ...
    initial_capital_reg < capital_grid(end), ...
    'Initial capital is not inside the Bellman capital grid.');

assert(ModelData.initial_savings >= savings_min && ...
    ModelData.initial_savings <= savings_max && ...
    terminal_savings >= savings_min && ...
    terminal_savings <= savings_max, ...
    'The Chapter 2 savings restrictions are outside the Bellman grid.');

% The no-anticipation Bellman problem assumes zero future hurricane loss.
no_risk_nodes = repmat({0},H_annual,1);
no_risk_weights = repmat({1},H_annual,1);

%% TERMINAL CONTINUATION VALUES
%
% The explicit model ends in 2300, but stopping welfare abruptly at the
% final year would distort savings near the horizon. A continuation
% value is therefore calculated under the imposed terminal savings rate.
%
% Two continuation values are computed:
%   1. without hurricane risk;
%   2. with the terminal hurricane-loss distribution.

[continuation_no_risk, ...
    continuation_iterations_no_risk] = ...
    fixed_savings_continuation( ...
    ModelData,capital_grid,terminal_savings, ...
    0,1,continuation_tolerance, ...
    continuation_max_iterations);

[continuation_hurricane_risk, ...
    continuation_iterations_hurricane] = ...
    fixed_savings_continuation( ...
    ModelData,capital_grid,terminal_savings, ...
    loss_nodes{end},loss_weights{end}, ...
    continuation_tolerance, ...
    continuation_max_iterations);

fprintf('Continuation iterations, without anticipation: %d\n', ...
    continuation_iterations_no_risk);

fprintf('Continuation iterations, hurricane-risk aware: %d\n', ...
    continuation_iterations_hurricane);

%% BELLMAN BACKWARD INDUCTION
%
% Solve the annual dynamic-programming problem backwards from the final
% model year to the first year.
%
% The first policy ignores future hurricane risk but can still respond
% to the capital stock inherited from earlier realised shocks.
% The second policy incorporates the expected annual hurricane-loss
% distribution when choosing savings.
%
% The resulting policy matrices map each (year, capital) state to an
% annual savings rate.

fprintf('\nSolving policy without hurricane anticipation...\n');

tic;

[value_no_risk,policy_no_risk, ...
    bellman_bounds_no_risk] = ...
    solve_bellman_policy( ...
    ModelData,capital_grid,savings_grid, ...
    no_risk_nodes,no_risk_weights, ...
    continuation_no_risk);

bellman_minutes_no_risk = toc./60;

fprintf('Solving hurricane-risk-aware policy...\n');

tic;

[value_hurricane_risk,policy_hurricane_risk, ...
    bellman_bounds_hurricane] = ...
    solve_bellman_policy( ...
    ModelData,capital_grid,savings_grid, ...
    loss_nodes,loss_weights, ...
    continuation_hurricane_risk);

bellman_minutes_hurricane = toc./60;

assert(all(isfinite(value_no_risk),'all') && ...
    all(isfinite(value_hurricane_risk),'all'), ...
    'A Bellman value function contains missing or infinite values.');

assert(all(policy_no_risk >= savings_min-1e-12,'all') && ...
    all(policy_no_risk <= savings_max+1e-12,'all') && ...
    all(policy_hurricane_risk >= savings_min-1e-12,'all') && ...
    all(policy_hurricane_risk <= savings_max+1e-12,'all'), ...
    'A Bellman savings policy lies outside the control bounds.');

fprintf('\n=== BELLMAN SOLUTION TIMES ===\n');

fprintf('Without hurricane anticipation: %.3f minutes\n', ...
    bellman_minutes_no_risk);

fprintf('Hurricane-risk aware:        %.3f minutes\n', ...
    bellman_minutes_hurricane);

fprintf('Without-anticipation grid clamps: %d\n', ...
    bellman_bounds_no_risk);

fprintf('Hurricane-risk-aware grid clamps: %d\n', ...
    bellman_bounds_hurricane);

%% FORWARD EVALUATION ON IDENTICAL HURRICANE HISTORIES
%
% After the two Bellman policies are solved, they are simulated forward
% on the SAME 10,000 out-of-sample hurricane histories. This makes the
% comparison paired: differences are caused by the savings rule rather
% than by different hurricane draws.
%
% Three cases are evaluated:
%   Reference              = fixed Chapter 2 savings pathway;
%   No anticipation        = feedback policy without hurricane risk;
%   Hurricane-risk-aware   = feedback policy with hurricane risk.

