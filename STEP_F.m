    Ytemperature_no_risk,Ynet_no_risk, ...
    Investment_no_risk,Consumption_no_risk, ...
    Savings_no_risk_realised,Welfare_no_risk, ...
    no_risk_grid_clamps] = ...
    simulate_policy( ...
    ModelData,capital_grid,policy_no_risk,[], ...
    hurricane_loss_eval);

[K_hurricane_risk,Ygross_hurricane_risk, ...
    Ytemperature_hurricane_risk,Ynet_hurricane_risk, ...
    Investment_hurricane_risk,Consumption_hurricane_risk, ...
